_SECURE_PUBLICATION_SUPPORTED = (
    os.name == "posix"
    and bool(getattr(os, "O_DIRECTORY", 0))
    and bool(getattr(os, "O_NOFOLLOW", 0))
    and all(
        function in getattr(os, "supports_dir_fd", set())
        for function in (
            os.open,
            os.stat,
            os.unlink,
            os.rename,
            os.link,
            os.mkdir,
            os.rmdir,
        )
    )
    and os.listdir in getattr(os, "supports_fd", set())
    and os.stat in getattr(os, "supports_follow_symlinks", set())
    and os.link in getattr(os, "supports_follow_symlinks", set())
)


class ImageOutputError(ValueError):
    """Raised when generated bytes cannot safely become the requested output."""


class _RetainedRecoveryAlreadyReportedError(ImageOutputError):
    """Cleanup failed after its retained recovery entry was already reported."""


class ImageStreamError(ImageOutputError):
    """Raised for a retryable transport failure while reading image bytes."""


class PublishedOutputError(ImageOutputError):
    """A post-install failure that still identifies the installed inode."""

    def __init__(self, message: str, device: int, inode: int):
        super().__init__(message)
        self.device = device
        self.inode = inode


class RemovedPublishedOutputError(PublishedOutputError):
    """A publisher proved it removed its own just-installed output."""


