class TemporaryOutput:
    descriptor: int
    parent_fd: int
    name: str
    device: int
    inode: int
    parent: ParentIdentity

    def __fspath__(self) -> str:
        return str(self.parent.path / self.name)

    def __str__(self) -> str:
        return os.fspath(self)


