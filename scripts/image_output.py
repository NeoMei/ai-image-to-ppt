TargetValue = Union[Path, PreparedTarget]


def require_secure_publication_primitives() -> None:
    """Fail closed when identity-bound publication is unavailable.

    The implementation requires POSIX directory-descriptor operations,
    no-follow metadata checks, hard links, and same-directory rename. A weaker
    pathname-only fallback would lose the documented ownership guarantees.
    """
    if not _SECURE_PUBLICATION_SUPPORTED:
        raise ImageOutputError(
            "secure output publication primitives are unavailable on this platform"
        )


def validate_retries(retries: object) -> int:
    if (
        isinstance(retries, bool)
        or not isinstance(retries, int)
        or retries < 0
        or retries > MAX_RETRIES
    ):
        raise ImageOutputError(
            f"retries must be a non-boolean integer >= 0 and at most {MAX_RETRIES}"
        )
    return retries


def _scan_json_structure(raw_response: object) -> None:
    """Bound JSON structure before the standard decoder allocates containers."""
    if not isinstance(raw_response, (str, bytes, bytearray)):
        raise ValueError("JSON input must be text or bytes")

    is_bytes = not isinstance(raw_response, str)
    if is_bytes:
        if raw_response.startswith((b"\xff\xfe", b"\xfe\xff", b"\x00\x00\xfe\xff", b"\xff\xfe\x00\x00")):
            raise ValueError("provider JSON must use UTF-8")
        index = 3 if raw_response.startswith(b"\xef\xbb\xbf") else 0
        quote, slash = 34, 92
        left_array, right_array = 91, 93
        left_object, right_object = 123, 125
        comma, colon = 44, 58
        whitespace = (9, 10, 13, 32)
    else:
        index = 0
        quote, slash = '"', "\\"
        left_array, right_array = "[", "]"
        left_object, right_object = "{", "}"
        comma, colon = ",", ":"
        whitespace = ("\t", "\n", "\r", " ")

    length = len(raw_response)
    stack = []
    root_state = "value"
    node_count = 0

    def skip_string(position: int) -> int:
        position += 1
        while position < length:
            current = raw_response[position]
            if current == slash:
                position += 2
                continue
            if current == quote:
                return position + 1
            position += 1
        raise ValueError("unterminated JSON string")

    def consume_value(position: int) -> int:
        nonlocal node_count, root_state
        if stack:
            context = stack[-1]
            if context[0] == "array":
                context[2] += 1
                if context[2] > MAX_JSON_CONTAINER_ITEMS:
                    raise ValueError("JSON container has too many items")
                context[1] = "comma_or_end"
            else:
                context[1] = "comma_or_end"
        else:
            root_state = "end"

        node_count += 1
        if node_count > MAX_JSON_NODES:
            raise ValueError("JSON has too many nodes")

        current = raw_response[position]
        if current == quote:
            return skip_string(position)
        if current in (left_array, left_object):
            if len(stack) > MAX_JSON_NESTING:
                raise ValueError("JSON nesting is too deep")
            if current == left_array:
                stack.append(["array", "value_or_end", 0])
            else:
                stack.append(["object", "key_or_end", 0])
            return position + 1

        start = position
        while position < length:
            current = raw_response[position]
            if current in whitespace or current in (comma, right_array, right_object):
                break
            position += 1
        if position == start:
            raise ValueError("expected JSON value")
        return position

    while True:
        while index < length and raw_response[index] in whitespace:
            index += 1

        if not stack:
            if root_state == "end":
                if index != length:
                    raise ValueError("trailing JSON data")
                return
            if index == length:
                raise ValueError("empty JSON input")
            index = consume_value(index)
            continue

        context = stack[-1]
        kind, state = context[0], context[1]
        if index == length:
            raise ValueError("incomplete JSON container")
        current = raw_response[index]

        if kind == "array":
            if state == "value_or_end" and current == right_array:
                stack.pop()
                index += 1
            elif state in ("value_or_end", "value"):
                index = consume_value(index)
            elif state == "comma_or_end" and current == comma:
                context[1] = "value"
                index += 1
            elif state == "comma_or_end" and current == right_array:
                stack.pop()
                index += 1
            else:
                raise ValueError("invalid JSON array structure")
            continue

        if state in ("key_or_end", "key"):
            if state == "key_or_end" and current == right_object:
                stack.pop()
                index += 1
            elif current == quote:
                context[2] += 1
                if context[2] > MAX_JSON_CONTAINER_ITEMS:
                    raise ValueError("JSON container has too many items")
                index = skip_string(index)
                context[1] = "colon"
            else:
                raise ValueError("invalid JSON object key")
        elif state == "colon" and current == colon:
            context[1] = "value"
            index += 1
        elif state == "value":
            index = consume_value(index)
        elif state == "comma_or_end" and current == comma:
            context[1] = "key"
            index += 1
        elif state == "comma_or_end" and current == right_object:
            stack.pop()
            index += 1
        else:
            raise ValueError("invalid JSON object structure")


def _object_without_duplicate_keys(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError("duplicate JSON object key")
        result[key] = value
    return result


def parse_json_response(raw_response: object) -> object:
    """Parse bounded provider JSON without leaking decoder recursion failures."""
    try:
        _scan_json_structure(raw_response)
        parsed = json.loads(
            raw_response,
            object_pairs_hook=_object_without_duplicate_keys,
        )
    except (TypeError, ValueError, UnicodeError, RecursionError) as error:
        raise ImageOutputError("provider response is not valid JSON") from error

    # CPython's JSON decoder recursion behavior differs by version. Enforce
    # deterministic resource limits with one iterator frame per active level;
    # never allocate one pending traversal tuple per sibling.
    stack = []
    value = parsed
    depth = 0
    node_count = 0
    while True:
        node_count += 1
        if node_count > MAX_JSON_NODES:
            raise ImageOutputError("provider response is not valid JSON")

        if isinstance(value, (dict, list)):
            if depth > MAX_JSON_NESTING or len(value) > MAX_JSON_CONTAINER_ITEMS:
                raise ImageOutputError("provider response is not valid JSON")
            children = value.values() if isinstance(value, dict) else value
            stack.append((iter(children), depth + 1))

        while stack:
            children, child_depth = stack[-1]
            try:
                value = next(children)
            except StopIteration:
                stack.pop()
                continue
            depth = child_depth
            break
        else:
            return parsed


def output_format(out_path: str) -> str:
    extension = Path(out_path).suffix.lower()
    try:
        return OUTPUT_FORMATS[extension]
    except KeyError as error:
        supported = ", ".join(sorted(OUTPUT_FORMATS))
        raise ImageOutputError(
            f"Unsupported output extension '{extension or '<none>'}'. Use: {supported}"
        ) from error


def expected_mime_type(out_path: str) -> str:
    return MIME_TYPES[output_format(out_path)]


def capture_path_base() -> Path:
    """Capture one absolute CWD for resolving every path in a public call."""
    try:
        return Path.cwd()
    except (OSError, ValueError, RuntimeError) as error:
        raise ImageOutputError(
            f"cannot capture current working directory: {error}"
        ) from error


def _absolute_path(value: object, base: Optional[Path]) -> Path:
    expanded = Path(value).expanduser()
    path_base = capture_path_base() if base is None else Path(base)
    if not path_base.is_absolute():
        raise ValueError("path base must be absolute")
    combined = expanded if expanded.is_absolute() else path_base / expanded
    absolute = Path(os.path.abspath(str(combined)))
    if "\0" in str(absolute):
        raise ValueError("embedded null byte")
    return absolute


def resolve_output_path(target: object, base: Optional[Path] = None) -> Path:
    """Freeze output ancestors as a real absolute path without following basename."""
    try:
        absolute = _absolute_path(target, base)
        return absolute.parent.resolve(strict=False) / absolute.name
    except (TypeError, ValueError, OSError, RuntimeError) as error:
        raise ImageOutputError(f"invalid output target: {error}") from error


def resolve_input_path(source: object, base: Optional[Path] = None) -> Path:
    """Freeze an input path, following its current final symlink referent."""
    try:
        return _absolute_path(source, base).resolve(strict=False)
    except (TypeError, ValueError, OSError, RuntimeError) as error:
        raise ImageOutputError(f"invalid input path: {error}") from error


def decode_base64(encoded: object) -> bytes:
    if not isinstance(encoded, str) or not encoded:
        raise ImageOutputError("image Base64 must be a non-empty string")
    max_encoded_bytes = 4 * ((MAX_IMAGE_BYTES + 2) // 3)
    if len(encoded) > max_encoded_bytes:
        raise ImageOutputError(
            f"image Base64 exceeds maximum encoded size of {max_encoded_bytes} bytes"
        )
    try:
        decoded = base64.b64decode(encoded, validate=True)
    except (binascii.Error, UnicodeError, ValueError) as error:
        raise ImageOutputError("image Base64 is invalid") from error
    if not decoded:
        raise ImageOutputError("image data is empty")
    if len(decoded) > MAX_IMAGE_BYTES:
        raise ImageOutputError(
            f"image data exceeds maximum size of {MAX_IMAGE_BYTES} bytes"
        )
    return decoded


def read_response_body(response) -> bytes:
    """Read one provider response with a hard maximum allocation boundary."""
    data = bytearray()
    remaining = MAX_PROVIDER_RESPONSE_BYTES + 1
    read_count = 0
    while remaining:
        if read_count >= MAX_PROVIDER_RESPONSE_READS:
            raise ImageOutputError("provider response returned too many chunks")
        read_count += 1
        try:
            chunk = response.read(
                min(PROVIDER_RESPONSE_READ_CHUNK_BYTES, remaining)
            )
        except TypeError as error:
            raise ImageOutputError(
                "provider response does not support bounded reads"
            ) from error
        except (OSError, http.client.HTTPException) as error:
            raise ImageStreamError(
                f"provider response read failed: {error}"
            ) from error
        if not isinstance(chunk, bytes):
            raise ImageOutputError("provider response body must be bytes")
        if not chunk:
            break
        data.extend(chunk[:remaining])
        remaining -= min(len(chunk), remaining)

    if len(data) > MAX_PROVIDER_RESPONSE_BYTES:
        raise ImageOutputError(
            "provider response exceeds maximum size of "
            f"{MAX_PROVIDER_RESPONSE_BYTES} bytes"
        )
    return bytes(data)


def read_bounded_image_stream(stream, max_bytes: int = MAX_IMAGE_BYTES) -> bytes:
    """Read image bytes without allowing an unbounded stream allocation."""
    if isinstance(max_bytes, bool) or not isinstance(max_bytes, int) or max_bytes <= 0:
        raise ImageOutputError("maximum image size must be a positive integer")

    headers = getattr(stream, "headers", {})
    try:
        content_length = headers.get("Content-Length")
    except AttributeError:
        content_length = None
    if content_length:
        try:
            declared_length = int(content_length)
        except (TypeError, ValueError) as error:
            raise ImageOutputError("download Content-Length is invalid") from error
        if declared_length < 0 or declared_length > max_bytes:
            raise ImageOutputError(
                f"download exceeds maximum image size of {max_bytes} bytes"
            )

    data = bytearray()
    max_reads = min(
        MAX_PROVIDER_RESPONSE_READS,
        (max_bytes + IMAGE_STREAM_READ_CHUNK_BYTES - 1)
        // IMAGE_STREAM_READ_CHUNK_BYTES + 1,
    )
    for _read_count in range(max_reads):
        remaining = max_bytes - len(data)
        try:
            chunk = stream.read(min(IMAGE_STREAM_READ_CHUNK_BYTES, remaining + 1))
        except TypeError as error:
            raise ImageOutputError("image stream does not support bounded reads") from error
        except (OSError, http.client.HTTPException) as error:
            raise ImageStreamError(f"image stream read failed: {error}") from error
        if not isinstance(chunk, bytes):
            raise ImageOutputError("image stream returned non-byte data")
        if not chunk:
            return bytes(data)
        data.extend(chunk)
        if len(data) > max_bytes:
            raise ImageOutputError(
                f"image data exceeds maximum size of {max_bytes} bytes"
            )
    raise ImageOutputError("image stream returned too many chunks")


def _validate_dimensions(width: int, height: int) -> None:
    if width <= 0 or height <= 0:
        raise ImageOutputError("image dimensions must be positive")
    if width * height > MAX_IMAGE_PIXELS:
        raise ImageOutputError(
            "image dimensions are too large; maximum pixel count is "
            f"{MAX_IMAGE_PIXELS}"
        )


def _load_image_data(
    data: bytes,
    verify: bool = False,
    copy_image: bool = True,
) -> LoadedImage:
    """Load one image under shared byte, pixel, and Pillow bomb limits."""
    try:
        if not isinstance(data, bytes) or not data:
            raise ImageOutputError("image data is empty")
        if len(data) > MAX_IMAGE_BYTES:
            raise ImageOutputError(
                f"image data exceeds maximum size of {MAX_IMAGE_BYTES} bytes"
            )
        byte_count = len(data)

        with warnings.catch_warnings():
            warnings.simplefilter("error", Image.DecompressionBombWarning)
            if verify:
                with Image.open(io.BytesIO(data)) as image:
                    _validate_dimensions(*image.size)
                    image.verify()
            with Image.open(io.BytesIO(data)) as image:
                width, height = image.size
                _validate_dimensions(width, height)
                image_format = image.format
                image.load()
                loaded = image.copy() if copy_image else None
    except ImageOutputError:
        raise
    except (Image.DecompressionBombError, Image.DecompressionBombWarning) as error:
        raise ImageOutputError(f"image dimensions are too large: {error}") from error
    except (OSError, SyntaxError, ValueError, UnidentifiedImageError) as error:
        raise ImageOutputError(f"data is not a valid image: {error}") from error

    return LoadedImage(loaded, image_format, byte_count, width, height)


def load_image(
    path: Path,
    verify: bool = False,
    copy_image: bool = True,
) -> LoadedImage:
    """Load one image under shared byte, pixel, and Pillow bomb limits."""
    image_path = Path(path)
    try:
        stated_size = image_path.stat().st_size
        if stated_size <= 0:
            raise ImageOutputError("image data is empty")
        if stated_size > MAX_IMAGE_BYTES:
            raise ImageOutputError(
                f"image exceeds maximum size of {MAX_IMAGE_BYTES} bytes"
            )
        with image_path.open("rb") as source:
            data = source.read(MAX_IMAGE_BYTES + 1)
        if len(data) > MAX_IMAGE_BYTES:
            raise ImageOutputError(
                f"image exceeds maximum size of {MAX_IMAGE_BYTES} bytes"
            )
    except ImageOutputError:
        raise
    except (OSError, ValueError) as error:
        raise ImageOutputError(f"data is not a valid image: {error}") from error
    return _load_image_data(data, verify=verify, copy_image=copy_image)


def validate_decoded_image_bytes(
    data: bytes,
    target: object,
    copy_image: bool = False,
) -> LoadedImage:
    """Validate bounded, decodable image bytes and the requested file format."""
    if not isinstance(data, bytes) or not data:
        raise ImageOutputError("image data must be non-empty bytes")
    if len(data) > MAX_IMAGE_BYTES:
        raise ImageOutputError(
            f"image data exceeds maximum size of {MAX_IMAGE_BYTES} bytes"
        )
    loaded = _load_image_data(data, verify=True, copy_image=copy_image)
    expected = PIL_FORMATS[output_format(str(target))]
    if loaded.image_format != expected:
        raise ImageOutputError(
            f"image format {loaded.image_format or '<unknown>'} does not match "
            f"{Path(str(target)).suffix.lower()}"
        )
    return loaded


def validate_image_bytes(data: bytes, target: object) -> LoadedImage:
    """Validate a provider output, including the strict 16:9 public boundary."""
    loaded = validate_decoded_image_bytes(data, target)
    if loaded.width * 9 != loaded.height * 16:
        raise ImageOutputError(
            f"generated image must be exactly 16:9; received "
            f"{loaded.width}x{loaded.height}"
        )
    return loaded


def prepare_target(target: Path) -> PreparedTarget:
    """Capture the parent directory identity for one output target."""
    try:
        output_path = Path(os.path.abspath(str(Path(target).expanduser())))
    except (TypeError, ValueError, OSError) as error:
        raise ImageOutputError(f"invalid output target: {error}") from error
    parent_path = output_path.parent
    try:
        parent_path.mkdir(parents=True, exist_ok=True)
        if parent_path.is_symlink():
            raise ImageOutputError(
                f"parent directory identity is unsafe: {parent_path} is a symlink"
            )
        real_path = parent_path.resolve(strict=True)
        parent_stat = parent_path.stat()
        if not stat.S_ISDIR(parent_stat.st_mode):
            raise ImageOutputError(
                f"parent directory identity is unsafe: {parent_path} is not a directory"
            )
    except ImageOutputError:
        raise
    except (OSError, ValueError) as error:
        raise ImageOutputError(
            f"cannot capture parent directory identity: {error}"
        ) from error
    return PreparedTarget(
        output_path,
        ParentIdentity(
            parent_path,
            real_path,
            parent_stat.st_dev,
            parent_stat.st_ino,
        ),
    )


def prepare_workspace_target(target: object, workspace_root: object) -> PreparedTarget:
    """Capture a writable output target that cannot leave a workspace root."""
    try:
        root = Path(workspace_root).expanduser().resolve(strict=True)
        if not root.is_dir():
            raise ImageOutputError("workspace root must be an existing directory")
        raw = Path(target).expanduser()
        if ".." in raw.parts:
            raise ImageOutputError("output target must not traverse outside workspace")
        absolute = raw if raw.is_absolute() else root / raw
        resolved = resolve_output_path(absolute, base=root)
        if resolved.parent != root and root not in resolved.parent.parents:
            raise ImageOutputError("output target escapes workspace root")
        prepared = prepare_target(resolved)
        if (
            prepared.parent.real_path != root
            and root not in prepared.parent.real_path.parents
        ):
            raise ImageOutputError("resolved output parent escapes workspace root")
        return prepared
    except ImageOutputError:
        raise
    except (OSError, TypeError, ValueError, RuntimeError) as error:
        raise ImageOutputError(f"invalid workspace target: {error}") from error


def verify_parent_identity(parent: ParentIdentity) -> None:
    """Fail closed if the captured output parent was replaced or redirected."""
    try:
        if parent.path.is_symlink():
            raise ImageOutputError(
                f"parent directory identity changed: {parent.path} is now a symlink"
            )
        current_real_path = parent.path.resolve(strict=True)
        current_stat = parent.path.stat()
        if (
            current_real_path != parent.real_path
            or current_stat.st_dev != parent.device
            or current_stat.st_ino != parent.inode
            or not stat.S_ISDIR(current_stat.st_mode)
        ):
            raise ImageOutputError(
                f"parent directory identity changed: {parent.path}"
            )
    except ImageOutputError:
        raise
    except (OSError, ValueError) as error:
        raise ImageOutputError(
            f"cannot verify parent directory identity: {error}"
        ) from error


def _as_prepared_target(target: TargetValue) -> PreparedTarget:
    if isinstance(target, PreparedTarget):
        return target
    return prepare_target(Path(target))


def prepared_lock_target(
    target: PreparedTarget,
    basename: Optional[str] = None,
) -> Path:
    """Build a stable lock key from a captured real parent directory."""
    name = target.name if basename is None else basename
    if not isinstance(name, str) or not name or Path(name).name != name:
        raise ImageOutputError("invalid output lock basename")
    return target.parent.real_path / name


def preflight_output(
    out_path: TargetValue,
    overwrite: bool = False,
) -> PreparedTarget:
    if not isinstance(overwrite, bool):
        raise ImageOutputError("overwrite must be a boolean")

    probe_path = None
    try:
        require_secure_publication_primitives()
        prepared = _as_prepared_target(out_path)
        target = prepared.path
        verify_parent_identity(prepared.parent)
        initial_identity = _capture_target_identity(prepared)
        if initial_identity is not None and not overwrite:
            raise ImageOutputError(
                f"output already exists; refusing to overwrite: {target}"
            )
        descriptor, probe_path = tempfile.mkstemp(
            prefix=".write-test.", dir=str(prepared.parent.path)
        )
        os.close(descriptor)
        verify_parent_identity(prepared.parent)
        os.unlink(probe_path)
        probe_path = None
        final_identity = _capture_target_identity(prepared)
        if final_identity != initial_identity:
            raise ImageOutputError("output identity changed during preflight")
    except ImageOutputError:
        raise
    except (OSError, ValueError) as error:
        raise ImageOutputError(f"output path is not writable: {error}") from error
    finally:
        if probe_path is not None:
            try:
                os.unlink(probe_path)
            except OSError:
                pass
    return replace(
        prepared,
        expected_identity=final_identity,
        expectation_captured=True,
    )


def _open_verified_parent(prepared: PreparedTarget) -> int:
    verify_parent_identity(prepared.parent)
    flags = os.O_RDONLY | getattr(os, "O_DIRECTORY", 0)
    flags |= getattr(os, "O_NOFOLLOW", 0)
    descriptor = None
    try:
        descriptor = os.open(str(prepared.parent.path), flags)
        current = os.fstat(descriptor)
        if (
            not stat.S_ISDIR(current.st_mode)
            or current.st_dev != prepared.parent.device
            or current.st_ino != prepared.parent.inode
        ):
            raise ImageOutputError("parent directory identity changed")
    except ImageOutputError:
        if descriptor is not None:
            try:
                os.close(descriptor)
            except OSError:
                pass
        raise
    except (OSError, TypeError, NotImplementedError) as error:
        if descriptor is not None:
            try:
                os.close(descriptor)
            except OSError:
                pass
        raise ImageOutputError(
            f"cannot open output parent directory: {error}"
        ) from error
    return descriptor


def _identity_at_parent_fd(parent_fd: int, name: str) -> Optional[Tuple[int, int]]:
    """Read one no-follow regular-file identity through a verified parent fd."""
    try:
        current = os.stat(name, dir_fd=parent_fd, follow_symlinks=False)
    except FileNotFoundError:
        return None
    except (OSError, TypeError, NotImplementedError) as error:
        raise ImageOutputError("cannot inspect output identity securely") from error
    if not stat.S_ISREG(current.st_mode):
        raise ImageOutputError("output path exists and is not a regular file")
    return current.st_dev, current.st_ino


def _capture_target_identity(prepared: PreparedTarget) -> Optional[Tuple[int, int]]:
    """Capture a target identity under its already-captured parent identity."""
    parent_fd = None
    try:
        parent_fd = _open_verified_parent(prepared)
        identity = _identity_at_parent_fd(parent_fd, prepared.name)
    finally:
        if parent_fd is not None:
            try:
                os.close(parent_fd)
            except OSError:
                pass
    verify_parent_identity(prepared.parent)
    return identity


def _verify_temporary_identity(temporary: TemporaryOutput) -> None:
    try:
        current = os.fstat(temporary.descriptor)
        parent = os.fstat(temporary.parent_fd)
        if (
            not stat.S_ISREG(current.st_mode)
            or current.st_dev != temporary.device
            or current.st_ino != temporary.inode
            or not stat.S_ISDIR(parent.st_mode)
            or parent.st_dev != temporary.parent.device
            or parent.st_ino != temporary.parent.inode
        ):
            raise ImageOutputError("output temporary file identity changed")
    except ImageOutputError:
        raise
    except OSError as error:
        raise ImageOutputError(
            f"cannot verify output temporary file identity: {error}"
        ) from error


def _verify_temporary_name(temporary: TemporaryOutput) -> None:
    try:
        current = os.stat(
            temporary.name,
            dir_fd=temporary.parent_fd,
            follow_symlinks=False,
        )
        if (
            not stat.S_ISREG(current.st_mode)
            or current.st_dev != temporary.device
            or current.st_ino != temporary.inode
        ):
            raise ImageOutputError("output temporary file identity changed")
    except ImageOutputError:
        raise
    except (OSError, TypeError, NotImplementedError) as error:
        raise ImageOutputError(
            f"cannot verify output temporary file name: {error}"
        ) from error


def _temporary_path(target: TargetValue) -> TemporaryOutput:
    prepared = _as_prepared_target(target)
    descriptor = None
    parent_fd = None
    temporary = None
    try:
        parent_fd = _open_verified_parent(prepared)
        flags = os.O_RDWR | os.O_CREAT | os.O_EXCL
        flags |= getattr(os, "O_NOFOLLOW", 0)
        for _attempt in range(100):
            name = f".{prepared.name}.{secrets.token_hex(16)}.tmp"
            try:
                descriptor = os.open(name, flags, 0o600, dir_fd=parent_fd)
                break
            except FileExistsError:
                continue
        else:
            raise ImageOutputError("failed to allocate unique output temporary file")
        temp_stat = None
        metadata_error = None
        for _attempt in range(2):
            try:
                temp_stat = os.fstat(descriptor)
                break
            except OSError as error:
                metadata_error = error
        if temp_stat is None:
            retained_path = str(prepared.parent.path / name)
            _warn_retained_temp(
                "temporary ownership could not be established; cleanup skipped",
                retained_path,
                metadata_error,
            )
            raise ImageOutputError(
                f"cannot identify output temporary file: {metadata_error}"
            ) from metadata_error
        if not stat.S_ISREG(temp_stat.st_mode):
            raise ImageOutputError("output temporary file is not regular")
        temporary = TemporaryOutput(
            descriptor,
            parent_fd,
            name,
            temp_stat.st_dev,
            temp_stat.st_ino,
            prepared.parent,
        )
        verify_parent_identity(prepared.parent)
        return temporary
    except (ImageOutputError, OSError, TypeError, NotImplementedError) as error:
        if temporary is not None:
            try:
                _remove_temp(temporary)
            except ImageOutputError:
                pass
            try:
                os.close(temporary.descriptor)
            except OSError:
                pass
        elif descriptor is not None:
            try:
                os.close(descriptor)
            except OSError:
                pass
        if parent_fd is not None:
            try:
                os.close(parent_fd)
            except OSError:
                pass
        raise ImageOutputError(f"failed to create output temporary file: {error}") from error


def _close_quarantine(quarantine: _QuarantinedOutput) -> None:
    try:
        os.close(quarantine.directory_fd)
    except OSError:
        pass


def _validate_recovery_directory_metadata(
    current: os.stat_result,
    expected_identity: Optional[Tuple[int, int]] = None,
) -> Tuple[int, int]:
    """Validate the ownership boundary for a private recovery namespace."""
    if not stat.S_ISDIR(current.st_mode):
        raise ImageOutputError("output recovery path is not a directory")
    identity = current.st_dev, current.st_ino
    if expected_identity is not None and identity != expected_identity:
        raise ImageOutputError("output recovery directory identity changed")
    geteuid = getattr(os, "geteuid", None)
    if callable(geteuid) and current.st_uid != geteuid():
        raise ImageOutputError("output recovery directory owner is not current user")
    if stat.S_IMODE(current.st_mode) != 0o700:
        raise ImageOutputError("output recovery directory permissions are not 0700")
    return identity


def _verify_bound_recovery_directory(
    quarantine: _QuarantinedOutput,
    *,
    require_public_name: bool = False,
    require_empty: bool = False,
) -> None:
    """Verify the open recovery directory and, optionally, its public name."""
    try:
        parent = os.fstat(quarantine.parent_fd)
        if (
            not stat.S_ISDIR(parent.st_mode)
            or parent.st_dev != quarantine.parent.device
            or parent.st_ino != quarantine.parent.inode
        ):
            raise ImageOutputError("output parent directory identity changed")
        current = os.fstat(quarantine.directory_fd)
        _validate_recovery_directory_metadata(
            current, quarantine.directory_identity
        )
        if require_public_name:
            public = os.stat(
                quarantine.directory_name,
                dir_fd=quarantine.parent_fd,
                follow_symlinks=False,
            )
            _validate_recovery_directory_metadata(
                public, quarantine.directory_identity
            )
        if require_empty and os.listdir(quarantine.directory_fd):
            raise ImageOutputError("output recovery directory is not empty")
    except ImageOutputError:
        raise
    except (OSError, TypeError, NotImplementedError) as error:
        raise ImageOutputError(
            f"cannot verify output recovery directory: {error}"
        ) from error


def _verify_bound_recovery_entry(
    quarantine: _QuarantinedOutput,
) -> None:
    """Verify the exact displaced entry through its bound private directory."""
    try:
        _verify_bound_recovery_directory(quarantine)
        current = os.stat(
            "entry",
            dir_fd=quarantine.directory_fd,
            follow_symlinks=False,
        )
        if (
            quarantine.identity is None
            or (current.st_dev, current.st_ino) != quarantine.identity
            or stat.S_ISREG(current.st_mode) != quarantine.is_regular
        ):
            raise ImageOutputError("output recovery entry identity changed")
    except ImageOutputError:
        raise
    except (OSError, TypeError, NotImplementedError) as error:
        raise ImageOutputError(
            f"cannot verify output recovery entry: {error}"
        ) from error


def _cleanup_recovery_directory(
    quarantine: _QuarantinedOutput,
    context: str,
) -> bool:
    """Remove one proven empty bound directory, or retain and report it.

    The public name is checked against the still-open directory immediately
    before removal.  A deliberate same-UID mutation at the final rmdir syscall
    boundary is outside the portable guarantee documented for this module.
    """
    cleanup_error = None
    try:
        _verify_bound_recovery_directory(
            quarantine,
            require_public_name=True,
            require_empty=True,
        )
        os.rmdir(quarantine.directory_name, dir_fd=quarantine.parent_fd)
        return True
    except (ImageOutputError, OSError, TypeError, NotImplementedError) as error:
        cleanup_error = error
        return False
    finally:
        _close_quarantine(quarantine)
        if cleanup_error is not None:
            _warn_retained_recovery(
                quarantine.parent,
                quarantine.directory_name,
                context,
                cleanup_error,
                entry=False,
            )


def _new_quarantine(
    parent_fd: int,
    parent: ParentIdentity,
) -> _QuarantinedOutput:
    """Allocate an unguessable mode-0700 directory for one displacement."""
    directory_name = None
    directory_fd = None
    try:
        parent_current = os.fstat(parent_fd)
        if (
            not stat.S_ISDIR(parent_current.st_mode)
            or parent_current.st_dev != parent.device
            or parent_current.st_ino != parent.inode
        ):
            raise ImageOutputError("output parent directory identity changed")
        for _attempt in range(100):
            candidate = f".image-output-recovery-{secrets.token_hex(16)}"
            try:
                os.mkdir(candidate, 0o700, dir_fd=parent_fd)
                directory_name = candidate
                break
            except FileExistsError:
                continue
        if directory_name is None:
            raise ImageOutputError("failed to allocate output recovery directory")
        created = os.stat(
            directory_name,
            dir_fd=parent_fd,
            follow_symlinks=False,
        )
        created_identity = _validate_recovery_directory_metadata(created)
        flags = os.O_RDONLY | getattr(os, "O_DIRECTORY", 0)
        flags |= getattr(os, "O_NOFOLLOW", 0)
        directory_fd = os.open(directory_name, flags, dir_fd=parent_fd)
        current = os.fstat(directory_fd)
        _validate_recovery_directory_metadata(current, created_identity)
        quarantine = _QuarantinedOutput(
            parent_fd,
            directory_fd,
            directory_name,
            created_identity,
            "",
            None,
            False,
            parent,
        )
        _verify_bound_recovery_directory(
            quarantine,
            require_public_name=True,
            require_empty=True,
        )
        return quarantine
    except (ImageOutputError, OSError, TypeError, NotImplementedError) as error:
        if directory_fd is not None:
            try:
                os.close(directory_fd)
            except OSError:
                pass
        if directory_name is not None:
            _warn_retained_recovery(
                parent,
                directory_name,
                "recovery directory ownership could not be established; cleanup skipped",
                error,
                entry=False,
            )
        if isinstance(error, ImageOutputError):
            raise
        raise ImageOutputError(
            f"failed to allocate output recovery directory: {error}"
        ) from error


def _displace_to_quarantine(
    parent_fd: int,
    parent: ParentIdentity,
    name: str,
) -> Optional[_QuarantinedOutput]:
    """Move the current name first, then identify the inode actually moved.

    The rename destination is inside a freshly created, identity-bound private
    directory.  The namespace is verified empty immediately before use.  A
    deliberate same-UID mutation inside that random private namespace remains
    outside the portable guarantee; public target races are preserved.
    """
    quarantine = _new_quarantine(parent_fd, parent)
    try:
        _verify_bound_recovery_directory(
            quarantine,
            require_public_name=True,
            require_empty=True,
        )
        os.rename(
            name,
            "entry",
            src_dir_fd=parent_fd,
            dst_dir_fd=quarantine.directory_fd,
        )
    except ImageOutputError as error:
        _cleanup_recovery_directory(
            quarantine,
            "untrusted recovery directory was retained",
        )
        raise ImageOutputError(
            f"failed to verify recovery directory before isolation: {error}"
        ) from error
    except FileNotFoundError:
        _cleanup_recovery_directory(
            quarantine,
            "unused recovery directory cleanup was incomplete",
        )
        return None
    except (OSError, TypeError, NotImplementedError) as error:
        _cleanup_recovery_directory(
            quarantine,
            "failed-isolation recovery directory cleanup was incomplete",
        )
        raise ImageOutputError(
            f"failed to isolate output before changing it: {error}"
        ) from error

    try:
        current = os.stat(
            "entry",
            dir_fd=quarantine.directory_fd,
            follow_symlinks=False,
        )
    except (OSError, TypeError, NotImplementedError) as error:
        retained_path = _retain_quarantine(
            quarantine,
            "isolated output identity is unknown; manual recovery is required",
            error,
        )
        raise ImageOutputError(
            "isolated output could not be identified; file retained at "
            f"{retained_path}"
        ) from error
    return replace(
        quarantine,
        original_name=name,
        identity=(current.st_dev, current.st_ino),
        is_regular=stat.S_ISREG(current.st_mode),
    )


def _retain_quarantine(
    quarantine: _QuarantinedOutput,
    context: str,
    error: Optional[Exception] = None,
) -> str:
    retained_path = str(quarantine.retained_path)
    _close_quarantine(quarantine)
    _warn_retained_recovery(
        quarantine.parent,
        quarantine.directory_name,
        context,
        error or ImageOutputError("manual recovery may be required"),
        entry=True,
    )
    return retained_path


def _restore_or_retain_quarantine(
    quarantine: _QuarantinedOutput,
    context: str,
) -> str:
    """Restore a displaced entry without clobbering, retaining a recovery copy."""
    restore_error = None
    try:
        _verify_bound_recovery_entry(quarantine)
        os.link(
            "entry",
            quarantine.original_name,
            src_dir_fd=quarantine.directory_fd,
            dst_dir_fd=quarantine.parent_fd,
            follow_symlinks=False,
        )
    except (ImageOutputError, OSError, TypeError, NotImplementedError) as error:
        restore_error = error
    return _retain_quarantine(quarantine, context, restore_error)


def _discard_quarantine(
    quarantine: _QuarantinedOutput,
    context: str,
) -> bool:
    """Best-effort cleanup inside the private recovery namespace.

    POSIX has no conditional unlink-by-inode.  The public pathname has already
    been displaced and checked; cleanup rechecks the bound random mode-0700
    recovery directory and entry identity immediately before unlink.  A
    deliberate same-UID mutation inside that private namespace at the unlink
    boundary is outside the portable guarantee.  Failures retain and report.
    """
    try:
        _verify_bound_recovery_entry(quarantine)
        os.unlink("entry", dir_fd=quarantine.directory_fd)
    except (ImageOutputError, OSError, TypeError, NotImplementedError) as error:
        _retain_quarantine(quarantine, context, error)
        return False
    _cleanup_recovery_directory(
        quarantine,
        "empty recovery directory cleanup was incomplete",
    )
    return True


def _remove_temp(path: Union[str, TemporaryOutput]) -> None:
    if isinstance(path, TemporaryOutput):
        _verify_temporary_identity(path)
        quarantined = _displace_to_quarantine(
            path.parent_fd,
            path.parent,
            path.name,
        )
        if quarantined is None:
            return
        expected = (path.device, path.inode)
        if not quarantined.is_regular or quarantined.identity != expected:
            retained_path = _restore_or_retain_quarantine(
                quarantined,
                "external temporary replacement was preserved",
            )
            raise ImageOutputError(
                "output temporary file identity changed; displaced file retained at "
                f"{retained_path}"
            )
        if not _discard_quarantine(
            quarantined,
            "temporary cleanup was incomplete",
        ):
            raise _RetainedRecoveryAlreadyReportedError(
                "failed to remove output temporary file; recovery entry retained"
            )
        return

    raise ImageOutputError(
        "output temporary file is not identity-bound; cleanup skipped"
    )


def _warn_retained_temp(context: str, path: str, error: Exception) -> None:
    try:
        print(
            safe_message(
                f"WARN: {context}; file remains at {path}: {error}"
            ),
            file=sys.stderr,
        )
    except Exception:
        pass


def _warn_retained_recovery(
    parent: ParentIdentity,
    directory_name: str,
    context: str,
    error: Exception,
    *,
    entry: bool,
) -> None:
    """Emit one bounded line with a complete, prioritized relative locator.

    The ASCII locator is constructed separately from the capped diagnostic
    detail, so a deep absolute target parent can never truncate the only
    recovery token.  Callers resolve it against the known output target parent.
    """
    try:
        allowed = frozenset("abcdefghijklmnopqrstuvwxyz0123456789-._")
        if (
            not isinstance(directory_name, str)
            or not directory_name.startswith(".image-output-recovery-")
            or not directory_name.isascii()
            or len(directory_name) > 96
            or any(character not in allowed for character in directory_name)
        ):
            raise ImageOutputError("invalid output recovery locator")
        locator = directory_name + ("/entry" if entry else "")
        absolute = parent.path / directory_name
        if entry:
            absolute /= "entry"
        prefix = (
            f"WARN: recovery={locator} relative-to-target-parent"
        )
        detail = safe_message(
            f"{context}; file remains at {absolute}: {error}"
        )
        print(f"{prefix}; {detail}", file=sys.stderr)
    except Exception:
        pass


def _cleanup_failed_temp(path: Union[str, TemporaryOutput]) -> None:
    try:
        _remove_temp(path)
    except _RetainedRecoveryAlreadyReportedError:
        pass
    except ImageOutputError as error:
        _warn_retained_temp("output failed", path, error)


def _validate_temp(
    path: Union[str, TemporaryOutput],
    target: TargetValue,
    validator=validate_image_bytes,
) -> int:
    prepared = _as_prepared_target(target)
    try:
        verify_parent_identity(prepared.parent)
        if isinstance(path, TemporaryOutput):
            _verify_temporary_identity(path)
            _verify_temporary_name(path)
            os.lseek(path.descriptor, 0, os.SEEK_SET)
            with os.fdopen(os.dup(path.descriptor), "rb") as stream:
                data = read_bounded_image_stream(stream)
            _verify_temporary_identity(path)
            _verify_temporary_name(path)
        else:
            with Path(path).open("rb") as stream:
                data = read_bounded_image_stream(stream)
        loaded = validator(data, prepared)
    except ImageOutputError:
        raise
    return loaded.byte_count


def _validate_opaque_bytes(data: bytes, _target: TargetValue) -> ValidatedBytes:
    """Accept bounded bytes for transaction compensation only.

    Existing output snapshots are allowed to be non-images because preflight
    protects filesystem safety, not image validity. New host data is validated
    before it reaches this recovery-only path.
    """
    return ValidatedBytes(len(data))


def _validate_expected_existing_identity(identity: object) -> tuple:
    if not isinstance(identity, tuple) or len(identity) != 2:
        raise ImageOutputError("expected output identity is invalid")
    device, inode = identity
    if (
        isinstance(device, bool)
        or isinstance(inode, bool)
        or not isinstance(device, int)
        or not isinstance(inode, int)
        or device < 0
        or inode < 0
    ):
        raise ImageOutputError("expected output identity is invalid")
    return identity


def remove_output_with_identity(
    target: TargetValue,
    expected_existing_identity: tuple,
) -> None:
    """Remove only the inode displaced from ``target`` at the rename boundary."""
    require_secure_publication_primitives()
    prepared = _as_prepared_target(target)
    expected = _validate_expected_existing_identity(expected_existing_identity)
    parent_fd = None
    quarantined = None
    try:
        parent_fd = _open_verified_parent(prepared)
        quarantined = _displace_to_quarantine(
            parent_fd,
            prepared.parent,
            prepared.name,
        )
        if quarantined is None:
            raise ImageOutputError("owned output disappeared before removal")
        if not quarantined.is_regular or quarantined.identity != expected:
            retained_path = _restore_or_retain_quarantine(
                quarantined,
                "external output replacement was preserved during removal",
            )
            quarantined = None
            raise ImageOutputError(
                "output identity changed during removal; displaced file retained at "
                f"{retained_path}"
            )
        try:
            verify_parent_identity(prepared.parent)
        except ImageOutputError:
            _restore_or_retain_quarantine(
                quarantined,
                "owned output was restored after parent verification failure",
            )
            quarantined = None
            raise
        _discard_quarantine(
            quarantined,
            "owned-output cleanup was incomplete",
        )
        quarantined = None
    finally:
        if quarantined is not None:
            _restore_or_retain_quarantine(
                quarantined,
                "owned output retained after incomplete removal",
            )
        if parent_fd is not None:
            try:
                os.close(parent_fd)
            except OSError:
                pass


def _remove_published_target(
    temporary: TemporaryOutput,
    name: str,
) -> bool:
    try:
        quarantined = _displace_to_quarantine(
            temporary.parent_fd,
            temporary.parent,
            name,
        )
        if quarantined is None:
            return False
        expected = (temporary.device, temporary.inode)
        if not quarantined.is_regular or quarantined.identity != expected:
            _restore_or_retain_quarantine(
                quarantined,
                "external published-output replacement was preserved",
            )
            return False
        _discard_quarantine(
            quarantined,
            "published-output cleanup was incomplete",
        )
        return True
    except ImageOutputError:
        return False


def _publish_temp(
    temp_path: Union[str, TemporaryOutput],
    target: TargetValue,
    overwrite: bool,
    expected_existing_identity: Optional[tuple] = None,
    expectation_captured: Optional[bool] = None,
) -> tuple:
    prepared = _as_prepared_target(target)
    if not isinstance(temp_path, TemporaryOutput):
        raise ImageOutputError("output temporary file is not identity-bound")
    installed_identity = None
    displaced = None
    try:
        verify_parent_identity(prepared.parent)
        _verify_temporary_identity(temp_path)
        _verify_temporary_name(temp_path)
        if expectation_captured is None:
            expectation_captured = prepared.expectation_captured
            expected_existing_identity = prepared.expected_identity
        if not expectation_captured:
            raise ImageOutputError("output publication expectation was not captured")
        if expected_existing_identity is not None:
            if not overwrite:
                raise ImageOutputError("existing output replacement was not authorized")
            displaced = _displace_to_quarantine(
                temp_path.parent_fd,
                prepared.parent,
                prepared.name,
            )
            if displaced is None:
                raise ImageOutputError("output identity changed before publication")
            if (
                not displaced.is_regular
                or displaced.identity != expected_existing_identity
            ):
                retained_path = _restore_or_retain_quarantine(
                    displaced,
                    "external output replacement was preserved",
                )
                displaced = None
                raise ImageOutputError(
                    "output identity changed before publication; displaced file "
                    f"retained at {retained_path}"
                )
        os.link(
            temp_path.name,
            prepared.name,
            src_dir_fd=temp_path.parent_fd,
            dst_dir_fd=temp_path.parent_fd,
            follow_symlinks=False,
        )
        installed_identity = (temp_path.device, temp_path.inode)
        published = os.stat(
            prepared.name,
            dir_fd=temp_path.parent_fd,
            follow_symlinks=False,
        )
        if (
            published.st_dev != temp_path.device
            or published.st_ino != temp_path.inode
            or not stat.S_ISREG(published.st_mode)
        ):
            raise ImageOutputError("published output identity changed")
        try:
            verify_parent_identity(prepared.parent)
        except ImageOutputError as error:
            if _remove_published_target(temp_path, prepared.name):
                if displaced is not None:
                    _restore_or_retain_quarantine(
                        displaced,
                        "previous output was restored after publication failure",
                    )
                    displaced = None
                raise RemovedPublishedOutputError(
                    str(error),
                    *installed_identity,
                ) from error
            installed_identity = None
            raise
        if displaced is not None:
            _discard_quarantine(
                displaced,
                "previous output cleanup was incomplete",
            )
            displaced = None
    except FileExistsError as error:
        if displaced is not None:
            _retain_quarantine(
                displaced,
                "previous output retained after concurrent target creation",
                error,
            )
            displaced = None
        raise ImageOutputError(
            f"output already exists; refusing to overwrite: {prepared.path}"
        ) from error
    except RemovedPublishedOutputError:
        raise
    except ImageOutputError as error:
        if installed_identity is not None:
            raise PublishedOutputError(
                str(error),
                *installed_identity,
            ) from error
        raise
    except (OSError, TypeError, NotImplementedError) as error:
        if displaced is not None:
            _restore_or_retain_quarantine(
                displaced,
                "previous output retained after publication failure",
            )
            displaced = None
        if installed_identity is not None:
            raise PublishedOutputError(
                "published output could not be verified",
                *installed_identity,
            ) from error
        raise ImageOutputError(
            f"failed to publish image without clobbering: {error}"
        ) from error
    finally:
        if displaced is not None:
            _retain_quarantine(
                displaced,
                "previous output retained after incomplete publication",
            )

    try:
        _remove_temp(temp_path)
    except _RetainedRecoveryAlreadyReportedError:
        pass
    except ImageOutputError as error:
        _warn_retained_temp(
            "output was published but cleanup failed", temp_path, error
        )
    return published.st_dev, published.st_ino


def _publish_image_bytes(
    data: bytes,
    target: TargetValue,
    overwrite: bool,
    validator,
    expected_existing_identity: Optional[tuple] = None,
    expected_missing: bool = False,
    allow_empty: bool = False,
) -> PublishedOutput:
    if not isinstance(data, bytes) or (not data and not allow_empty):
        raise ImageOutputError("image data must be non-empty bytes")
    if len(data) > MAX_IMAGE_BYTES:
        raise ImageOutputError(
            f"image data exceeds maximum size of {MAX_IMAGE_BYTES} bytes"
        )
    prepared = _as_prepared_target(target)
    if expected_missing:
        prepared = replace(
            prepared,
            expected_identity=None,
            expectation_captured=True,
        )
    elif expected_existing_identity is not None:
        prepared = replace(
            prepared,
            expected_identity=_validate_expected_existing_identity(
                expected_existing_identity
            ),
            expectation_captured=True,
        )
    elif not prepared.expectation_captured:
        prepared = preflight_output(prepared, overwrite=overwrite)
    temporary = _temporary_path(prepared)
    published = False
    try:
        with os.fdopen(os.dup(temporary.descriptor), "wb") as output:
            output.write(data)
            output.flush()
            os.fsync(output.fileno())
        if validator is validate_image_bytes:
            byte_count = _validate_temp(temporary, prepared)
        else:
            byte_count = _validate_temp(temporary, prepared, validator)
        identity = _publish_temp(temporary, prepared, overwrite)
        published = True
        return PublishedOutput(byte_count, *identity)
    except ImageOutputError:
        raise
    except (OSError, TypeError, NotImplementedError) as error:
        raise ImageOutputError(f"failed to write image: {error}") from error
    finally:
        if not published:
            _cleanup_failed_temp(temporary)
        try:
            os.close(temporary.descriptor)
        except OSError:
            pass
        try:
            os.close(temporary.parent_fd)
        except OSError:
            pass


def publish_bytes(data: bytes, target: TargetValue, overwrite: bool = False) -> int:
    """Publish an image only when it passes the strict shared 16:9 boundary."""
    return publish_bytes_with_identity(data, target, overwrite).byte_count


def publish_bytes_with_identity(
    data: bytes,
    target: TargetValue,
    overwrite: bool = False,
) -> PublishedOutput:
    """Strictly publish an image and return the exact installed inode."""
    return _publish_image_bytes(data, target, overwrite, validate_image_bytes)


def publish_decoded_image_bytes(
    data: bytes,
    target: TargetValue,
    overwrite: bool = False,
) -> int:
    """Publish bounded image bytes after format/decode validation only.

    This is for retaining an immutable raw artifact before a caller applies a
    stricter, source-specific transform. It must not be used for API outputs.
    """
    return publish_decoded_image_bytes_with_identity(
        data, target, overwrite
    ).byte_count


def publish_decoded_image_bytes_with_identity(
    data: bytes,
    target: TargetValue,
    overwrite: bool = False,
) -> PublishedOutput:
    """Publish decode-validated bytes and return the exact installed inode."""
    return _publish_image_bytes(
        data,
        target,
        overwrite,
        validate_decoded_image_bytes,
    )


def publish_opaque_bytes_with_identity(
    data: bytes,
    target: TargetValue,
    *,
    expected_existing_identity: tuple,
) -> PublishedOutput:
    """Restore bounded snapshot bytes over one exact, identity-bound output.

    This intentionally bypasses image validation: snapshots predate a failed
    host transaction and may be arbitrary regular-file bytes. The expected
    inode prevents compensation from replacing a different current file.
    """
    expected_identity = _validate_expected_existing_identity(
        expected_existing_identity
    )
    return _publish_opaque_bytes(
        data,
        target,
        expected_identity,
    )


def publish_opaque_bytes_if_missing(
    data: bytes,
    target: TargetValue,
) -> PublishedOutput:
    """Restore opaque snapshot bytes only if no current pathname exists."""
    return _publish_image_bytes(
        data,
        target,
        False,
        _validate_opaque_bytes,
        expected_missing=True,
        allow_empty=True,
    )


def _publish_opaque_bytes(
    data: bytes,
    target: TargetValue,
    expected_existing_identity: tuple,
) -> PublishedOutput:
    """Atomically restore bounded opaque bytes, including an empty snapshot."""
    return _publish_image_bytes(
        data,
        target,
        True,
        _validate_opaque_bytes,
        expected_existing_identity=expected_existing_identity,
        allow_empty=True,
    )


def publish_stream(
    response,
    target: TargetValue,
    overwrite: bool = False,
    max_bytes: int = MAX_IMAGE_BYTES,
) -> int:
    headers = getattr(response, "headers", {})
    content_length = None
    try:
        content_length = headers.get("Content-Length")
    except AttributeError:
        pass
    if content_length:
        try:
            declared_length = int(content_length)
        except (TypeError, ValueError) as error:
            raise ImageOutputError("download Content-Length is invalid") from error
        if declared_length < 0 or declared_length > max_bytes:
            raise ImageOutputError(
                f"download exceeds maximum image size of {max_bytes} bytes"
            )

    prepared = _as_prepared_target(target)
    if not prepared.expectation_captured:
        prepared = preflight_output(prepared, overwrite=overwrite)
    temporary = _temporary_path(prepared)
    published = False
    try:
        byte_count = 0
        with os.fdopen(os.dup(temporary.descriptor), "wb") as output:
            while True:
                try:
                    chunk = response.read(64 * 1024)
                except (OSError, http.client.HTTPException) as error:
                    raise ImageStreamError(f"image download failed: {error}") from error
                if not chunk:
                    break
                if not isinstance(chunk, bytes):
                    raise ImageOutputError("download returned non-byte image data")
                byte_count += len(chunk)
                if byte_count > max_bytes:
                    raise ImageOutputError(
                        f"download exceeds maximum image size of {max_bytes} bytes"
                    )
                output.write(chunk)
            output.flush()
            os.fsync(output.fileno())
        byte_count = _validate_temp(temporary, prepared)
        _publish_temp(temporary, prepared, overwrite)
        published = True
        return byte_count
    except ImageOutputError:
        raise
    except (OSError, TypeError, NotImplementedError) as error:
        raise ImageOutputError(f"failed to download image: {error}") from error
    finally:
        if not published:
            _cleanup_failed_temp(temporary)
        try:
            os.close(temporary.descriptor)
        except OSError:
            pass
        try:
            os.close(temporary.parent_fd)
        except OSError:
            pass
